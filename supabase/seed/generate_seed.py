class Org:
    def __init__(self, org_id, key):
        self.id = org_id
        self.key = key
        self.customers, self.contacts, self.enquiries, self.events = [], [], [], []
        self.quotes, self.sections, self.items, self.versions = [], [], [], []
        self.invoices, self.payments, self.threads, self.messages = [], [], [], []
        self.tasks, self.activity, self.notifications, self.cal_events = [], [], [], []
        self.documents, self.event_contacts = [], []
        self.enq_n = 1000
        self.ev_n = 2000
        self.q_n = 1000
        self.inv_n = 1000

    def k(self, *parts):
        return uid(self.key + ":" + ":".join(parts))

    def log(self, when, action, entity_type, entity_id, summary, actor=None, actor_type="user",
            actor_label=None, event_id=None, customer_id=None, enquiry_id=None, changes=None, metadata=None):
        self.activity.append(dict(
            organisation_id=self.id, actor_id=actor, actor_type=actor_type, actor_label=actor_label,
            action=action, entity_type=entity_type, entity_id=entity_id, customer_id=customer_id,
            event_id=event_id, enquiry_id=enquiry_id, summary=summary, changes=changes, metadata=metadata,
            created_at=when))


def line_total(ln) -> Decimal:
    return money(Decimal(str(ln["qty"])) * Decimal(str(ln["price"])) * (1 - Decimal(str(ln.get("disc", 0))) / 100))


def quote_totals(lines):
    sub = sum((line_total(ln) for ln in lines if not ln.get("optional")), Decimal("0"))
    sub = money(sub)
    tax = money(sub * Decimal("0.1"))
    return sub, tax, money(sub + tax)


def build_quote(o: Org, key, event, customer, title, sections, *, status, versions,
                issue_days, expiry_days, notes=None, terms=None, unpublished=False):
    """sections: list of (title, [line dicts]); versions: list of (status, published_minutes_ago, extra)"""
    o.q_n += 1
    qid = o.k("quote", key)
    all_lines = [ln for _, lines in sections for ln in lines]
    sub, tax, total = quote_totals(all_lines)
    for si, (stitle, lines) in enumerate(sections):
        sid = o.k("qsec", key, str(si))
        o.sections.append(dict(id=sid, organisation_id=o.id, quote_id=qid, title=stitle,
                               description=None, position=si, is_optional=False))
        for li, ln in enumerate(lines):
            o.items.append(dict(organisation_id=o.id, quote_id=qid, section_id=sid, name=ln["name"],
                                description=ln.get("desc"), quantity=ln["qty"], unit=ln.get("unit"),
                                unit_price=ln["price"], tax_rate=10, discount_percent=ln.get("disc", 0),
                                is_optional=bool(ln.get("optional")), is_package=bool(ln.get("package")),
                                position=li))

    current = None
    for vi, (vstatus, mins_ago, extra) in enumerate(versions, start=1):
        vid = o.k("qver", key, str(vi))
        current = vid
        # earlier versions carry a slightly different total to show history
        v_sub, v_tax, v_total = (sub, tax, total)
        v_snap = Raw(f"demo.quote_snapshot('{qid}')")
        if vi < len(versions):
            v_sub = money(sub * Decimal("0.9"))
            v_tax = money(v_sub * Decimal("0.1"))
            v_total = money(v_sub + v_tax)
            v_snap = Raw(f"demo.quote_snapshot('{qid}', 0.9)")
        o.versions.append(dict(
            id=vid, organisation_id=o.id, quote_id=qid, version_number=vi, snapshot=v_snap,
            subtotal=v_sub, tax_total=v_tax, total=v_total, status=Raw(f"'{vstatus}'"),
            published_at=AGO(mins_ago), published_by=extra.get("by"),
            viewed_at=AGO(extra["viewed"]) if extra.get("viewed") else None,
            responded_at=AGO(extra["responded"]) if extra.get("responded") else None,
            accepted_by_name=extra.get("accepted_by"),
            acceptance_ip=Raw("'203.0.113.24'::inet") if extra.get("accepted_by") else None,
            acceptance_user_agent="Mozilla/5.0 (iPhone; CPU iPhone OS 18_5 like Mac OS X)" if extra.get("accepted_by") else None,
            decline_reason=None))
    o.quotes.append(dict(
        id=qid, organisation_id=o.id, number=o.q_n, event_id=event["id"], customer_id=customer["id"],
        title=title, status=Raw(f"'{status}'"), issue_date=D(issue_days), expiry_date=D(expiry_days),
        notes=notes, terms=terms, current_version_id=None, has_unpublished_changes=unpublished,
        created_by=event["assigned_to"], _current=current))
    return dict(id=qid, number=o.q_n, sub=sub, tax=tax, total=total)


def add_invoice(o: Org, key, customer, event, quote, kind, amount_total, issue_days, due_days, status,
                paid=0.0, paid_minutes_ago=None, method="Bank transfer"):
    o.inv_n += 1
    iid = o.k("inv", key)
    total = money(amount_total)
    sub = money(total / Decimal("1.1"))
    tax = money(total - sub)
    o.invoices.append(dict(
        id=iid, organisation_id=o.id, number=f"INV-{o.inv_n}", customer_id=customer["id"],
        event_id=event["id"] if event else None, quote_id=quote["id"] if quote else None, kind=kind,
        issue_date=D(issue_days), due_date=D(due_days), subtotal=sub, tax_total=tax, total=total,
        amount_paid=money(paid), status=Raw(f"'{status}'")))
    if paid > 0:
        o.payments.append(dict(organisation_id=o.id, invoice_id=iid, amount=money(paid),
                               paid_at=AGO(paid_minutes_ago), method=method,
                               reference=f"INV-{o.inv_n}"))
    return dict(id=iid, number=f"INV-{o.inv_n}", total=total)


def thread(o: Org, key, subject, classification, state, messages, *, customer=None, event=None,
           enquiry=None, confidence=0.95, classified_by="rules"):
    tid = o.k("thread", key)
    parts = sorted({m["from_email"] for m in messages} | {e for m in messages for e in m["to"]})
    last = min(m["ago"] for m in messages)
    inbound = [m["ago"] for m in messages if m["dir"] == "inbound"]
    o.threads.append(dict(
        id=tid, organisation_id=o.id, gmail_thread_id=f"demo-{key}", subject=subject,
        customer_id=customer["id"] if customer else None, event_id=event["id"] if event else None,
        enquiry_id=enquiry["id"] if enquiry else None, classification=Raw(f"'{classification}'"),
        classification_confidence=confidence, classified_by=classified_by, state=state,
        participants=parts, message_count=len(messages), last_message_at=AGO(last),
        last_inbound_at=AGO(min(inbound)) if inbound else None))
    for mi, m in enumerate(messages):
        o.messages.append(dict(
            organisation_id=o.id, thread_id=tid, gmail_message_id=f"demo-{key}-{mi}",
            direction=m["dir"], from_email=m["from_email"], from_name=m["from_name"], to_emails=m["to"],
            subject=subject if mi == 0 else "Re: " + subject, snippet=m["body"][:140].replace("\n", " "),
            body_text=m["body"], sent_at=AGO(m["ago"]), is_read=m.get("read", True),
            sent_by=m.get("by")))
    return tid


def msg(direction, from_email, from_name, to, ago, body, by=None, read=True):
    return dict(dir=direction, from_email=from_email, from_name=from_name, to=to, ago=ago, body=body,
                by=by, read=read)


