def insert(table: str, rows: list[dict]):
    if not rows:
        return
    cols = list(rows[0].keys())
    for r in rows:
        assert list(r.keys()) == cols, f"{table}: column mismatch {r.keys()} vs {cols}"
    values = ",\n  ".join("(" + ", ".join(q(r[c]) for c in cols) + ")" for r in rows)
    out.append(f"insert into public.{table} ({', '.join(cols)}) values\n  {values};\n")


