class UID(str):
    """A deterministic uuid5; emitted in SQL as demo.u('key') to keep the file small."""
    key: str


def uid(key: str) -> "UID":
    u = UID(str(uuid.uuid5(NS, key)))
    u.key = key
    return u


def q(v):
    """SQL literal."""
    if v is None:
        return "null"
    if isinstance(v, UID):
        return f"demo.u('{v.key}')"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, Decimal):
        return str(v)
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, Raw):
        return v.sql
    if isinstance(v, (list, tuple)):
        return "array[" + ",".join(q(x) for x in v) + "]::text[]" if v else "'{}'::text[]"
    if isinstance(v, dict):
        return q(json.dumps(v)) + "::jsonb"
    return "'" + str(v).replace("'", "''") + "'"


class Raw:
    def __init__(self, sql):
        self.sql = sql


