def D(days: int) -> Raw:
    """A date relative to today (Sydney)."""
    return Raw(f"demo.d({days})")


def AT(days: int, hhmm: str) -> Raw:
    """A timestamptz on a Sydney-local day/time."""
    return Raw(f"demo.at({days},'{hhmm}')")


def AGO(minutes) -> Raw:
    return Raw(f"demo.ago({int(minutes)})")


def AHEAD(minutes) -> Raw:
    return Raw(f"demo.ago({-int(minutes)})")


def money(x) -> Decimal:
    return Decimal(str(x)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


